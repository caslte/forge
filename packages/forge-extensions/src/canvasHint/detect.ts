/**
 * 出图意图判定（纯函数，node:test 回归）。
 *
 * 只认「名词级出图请求」：用户话里出现了图的具体体裁（流程图/时序图/架构图…）、
 * 命中「画/绘+图」动词短语正则、或有明确的画图动词（visualize），才把完整输出
 * 规范塞进本轮系统提示。
 *
 * 旧版刻意偏松（「讲清楚机制 / 对比一下 / explain」这类主题泛词也命中），赌的是
 * 「多命中只多花 200 token，模型自己会判断要不要画」——真机验证输了：契约一注入，
 * 模型就把它读成「本轮该画」，纯文字说明也被包进 canvas 围栏，产出大量「文字塞
 * 卡片」的伪图示（用户实测抱怨的正是这个）。故收窄为：泛主题词一律不命中，画的
 * 口味交还给常驻段——内容真有空间结构时模型仍可自发出卡，只是没人推着每轮都画。
 *
 * 误判的代价依旧不对称，但方向反过来：多命中 = 200 token + 一次画图倾向；
 * 漏命中 = 结构化 markdown 照样把机制讲清楚，用户真想看图会说「图」。
 * ——漏网一语成谶（2026-09-29 真机）：「你画一个图」不在四个字面表里，契约没
 * 注入，模型凭常驻段幻觉出「pi 原生 canvas 渲染 ASCII」交了裸 mermaid。故动词
 * 类从字面表改正则枚举；体裁名词表不动，泛主题词照旧一律不命中。
 */

/** 中文意图信号：图的具体体裁（名词级，字面匹配即可），不含主题泛词 */
const ZH_GENRE_PATTERNS: readonly string[] = [
  '流程图',
  '时序图',
  '架构图',
  '示意图',
  '原理图',
  '结构图',
  '关系图',
  '状态机图',
  '拓扑',
  '图解',
  '图示',
  '可视化',
];

/**
 * 中文「画图动词」短语正则（2026-09-29 由字面词表改来）。
 *
 * 旧表只有 画图/画个图/画张图/画一张图 四个字面，「你画一个图」差一个字就漏网
 * （真机：漏网轮契约没注入，模型凭常驻段幻觉出「pi 原生 canvas 渲染 ASCII」）。
 * 画/绘 × 数量词的变体是有限闭集，枚举组合比 `画.{0,3}图` 这类通配准——通配会
 * 把「画布图」「画出来的图」连上，还顺着句子跨到后半句的「图」字。
 * 「整/来」两条锚行首：「整张图」「整一个图」在句中都可能是别的意思（「把这张
 * 图发我」里没有画义），只有开头祈使式才稳。
 */
const ZH_DRAW_RES: readonly RegExp[] = [
  /[画绘][一两三几]?[张幅个下]?图/,
  /^[整来][一两三几]?[张幅个]?图/,
];

/**
 * 改图 / 重出信号（2026-10-10 真机漏网修复）。
 *
 * 真机实测：用户说「重新画一下」全部漏网 ⇒ 只注入常驻段 ⇒ 模型不知道 IR 长什么样
 * ⇒ 退回手写 HTML + `cat > /tmp/x.html` 写文件（截图证实）。
 *
 * 这些词**不含「图」字**（"重新画一下"里没有图），所以原有两条正则都抓不到。
 * 单独成表而不是并入 ZH_GENRE_PATTERNS：它们是「动作」信号而非「体裁」信号，
 * 混在一起会让「重画」被误当成一种图的体裁。
 */
const ZH_REDO_RES: readonly RegExp[] = [
  /重新?画/,
  /再画/,
  /重画/,
  /换个.{0,4}画/,
  /换.{0,3}方式画/,
  /再来一[版个]/,
  /重新?出.{0,2}[版个]/,
  // 对图的质量抱怨：命中即可，不必等用户明说「重画」。
  // 取舍依据本文件既有的不对称原则：多命中 = 200 token + 一次画图倾向；
  // 漏命中 = 模型不响应用户抱怨（真机已有过漏网事故）。故偏宽松。
  // 但要求确实在抱怨**图**（带「图」字或「难看/太丑」），避免把对代码/方案的
  // 抱怨（「这段代码太丑」）也算成出图意图。
  /图.{0,6}(不好看|不对|太丑|不清楚|太密|太挤|错了|难看)/,
  /(难看|太丑|不好看).{0,4}(图|卡片|布局|排版)/,
];

/**
 * 受限放宽的体裁词（2026-10-10）。
 *
 * 「架构」「结构」这类词在真机里非常常用（「梳理一下项目架构」），但**单独不能命中**
 * —— 否则就回到 2026-09 那次收窄的老坑：泛主题词命中会让模型把纯文字说明也包成卡片，
 * 产出大量「文字塞卡片」伪图示（用户当时实测抱怨的正是这个）。
 *
 * 故限定为**必须与出图意图动词共现**。词表刻意短，只收真正常搭配的。
 */
const ZH_TOPIC_PATTERNS: readonly string[] = ['架构', '结构'];
const ZH_INTENT_VERBS: readonly RegExp[] = [
  /梳理|理清|整理|分析|画|绘|出一版|给我|来个|展示|看看|看下|看一下|过一遍|浏览/,
];

/** 英文意图信号（界面中英双语，提示词也可能是英文） */
const EN_PATTERNS: readonly string[] = [
  'diagram',
  'flowchart',
  'flow chart',
  'sequence diagram',
  'architecture diagram',
  'state diagram',
  'visualize',
  'visualise',
  'illustrate',
  'draw a',
  'draw me',
  'sketch a',
  'chart',
];

/**
 * 判定本轮是否值得注入完整画布输出规范。
 *
 * 英文按小写子串匹配：这些词都是完整单词或短语，作为子串误伤面极小
 * （"chart" 会命中 "flowchart"，方向一致；"draw a" 不受 "drawback" 干扰）。
 */
export function looksLikeDiagramRequest(prompt: string): boolean {
  const text = (prompt ?? '').trim();
  if (text === '') return false;
  if (ZH_GENRE_PATTERNS.some((k) => text.includes(k))) return true;
  if (ZH_DRAW_RES.some((re) => re.test(text))) return true;
  // 改图信号：不含「图」字，只能靠动作词命中（真机漏网修复）
  if (ZH_REDO_RES.some((re) => re.test(text))) return true;
  // 受限放宽：体裁词 + 意图动词共现才命中，避免泛主题词全命中
  if (
    ZH_TOPIC_PATTERNS.some((k) => text.includes(k)) &&
    ZH_INTENT_VERBS.some((re) => re.test(text))
  ) {
    return true;
  }
  const lower = text.toLowerCase();
  return EN_PATTERNS.some((k) => lower.includes(k));
}
